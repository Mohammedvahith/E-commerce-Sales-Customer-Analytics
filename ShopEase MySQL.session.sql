        SUM(oi.total_amount) AS monthly_revenue
    FROM orders o
    INNER JOIN order_items oi
        ON o.order_id = oi.order_id
    GROUP BY DATE_FORMAT(o.orders_date, '%Y-%m')
),
previous_revenue as (
    select
        sales_month,
        lag(monthly_revenue) over(
        order by sales_month) as previous_revenue
    from monthly_revenue
),
MoM_growth as (
    select 
        ROUND(((m.monthly_revenue-p.previous_revenue)/p.previous_revenue)*100,2) as MoM_growth
    from monthly_revenue m 
    INNER join previous_revenue p 
    on m.sales_month = p.sales_month
    order by m.sales_month
)

select max(MoM_growth) as MAX_MoM_Growth,min(MoM_growth) as Min_MoM_Growth
from MoM_growth;

-- 20 - Business KPI Analysis — Order Status & Completion Rate.
-- Out of all the orders customers placed, how many were successfully delivered, cancelled, returned or are still pending?

select 
    a.order_status,
    a.status_count,
    round(
        a.status_count/ sum(a.status_count) over()*100,2) as status_percentage
