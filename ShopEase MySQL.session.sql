--  1 - Total number of customers in your dataset
SELECT city,COUNT(*) AS "Total No Of Customer"
FROM customers
GROUP BY city
ORDER BY COUNT(*) DESC;

-- 2 - Average customer age by city
SELECT city,ROUND(AVG(age),2) AS avg_age
FROM customers
GROUP BY city;

-- 3 - Combine aggregate functions
/*
Business question: For each city, find:
1. Total number of customers.
2. Average customer age.
3. Youngest customer age.
4. Oldest customer age.
*/

SELECT 
    city,
    COUNT(*) AS "Total number of customers",
    ROUND(AVG(AGE),2) AS "Average customer age",
    MIN(AGE) AS "Youngest customer age",
    MAX(AGE) AS "Oldest customer age"
FROM customers
GROUP BY city;

-- 4 - Business question - Find cities that have more than 1,000 registered customers.
SELECT city,COUNT(*) AS Total_Customer
FROM customers
GROUP BY city
HAVING Total_Customer >= 1000;

-- 5 - Business question 
/* 
Find cities where:
1. We consider only customers aged 30 or older.
2. The number of qualifying customers in that city must be greater than 500.
*/
SELECT 
    city,
    COUNT(*) AS qualifying_customers,
    ROUND(AVG(age)) AS avg_age
FROM customers
WHERE age >= 30
GROUP BY city
HAVING qualifying_customers > 500;

-- 6 - Business question - How much total money was generated by each product category?

SELECT * FROM products;
SELECT * FROM order_items;

SELECT
    p.category AS Category,
    ROUND(SUM(oi.total_amount), 2) AS Total_Amount
FROM products p
INNER JOIN order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.category
ORDER BY Total_Amount DESC;