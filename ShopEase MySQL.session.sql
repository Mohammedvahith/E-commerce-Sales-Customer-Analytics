-- 23 - Category return-rate analysis
/*
Business question: 
Which product category has 
the highest return rate?
*/
WITH category_orders AS (
    SELECT
        p.category,
        COUNT(DISTINCT CASE
            WHEN o.order_status = 'Delivered'
            THEN o.order_id
        END) AS delivered_orders,

        COUNT(DISTINCT CASE
            WHEN o.order_status = 'Returned'
            THEN o.order_id
        END) AS returned_orders

    FROM orders o
    INNER JOIN order_items oi
        ON o.order_id = oi.order_id
    INNER JOIN products p
        ON oi.product_id = p.product_id

    WHERE o.order_status IN ('Delivered', 'Returned')

    GROUP BY p.category
)

SELECT
    category,
    delivered_orders,
    returned_orders,

    ROUND(
        returned_orders * 100.0 /
        NULLIF(delivered_orders + returned_orders, 0),
        2
    ) AS return_rate

FROM category_orders
ORDER BY return_rate DESC;

-- 24 - Customer analysis
/*
Who are the highest-spending customers?
How many customers are repeat customers?
Which customers contribute the most revenue?
*/

with customer_orders as (
    select 
        customer_id,
        count(order_id) as total_orders
    from orders
    group by customer_id
)

select 
    count(*) as Total_Customer,
    sum(
        case
            when total_orders = 1 then 1
            else 0
        end
    ) as one_time_customers,
    sum(
        case
            when total_orders > 1 then 1
            else 0
        end
    ) as repeat_customers,
    round(
        (
        sum(
            case
                when total_orders > 1 then 1
                else 0
            end
            )
        )
        /
        count(*)
        *100,
        2
        )AS repeat_customers_rate
from customer_orders

-- 25 - Top 10 highest-spending customers
/*
Who are the 10 customers generating the highest revenue?

We will use:
- customers
- orders
- order_items
- SUM() to calculate customer revenue.
- ORDER BY and LIMIT to find the top 10.
*/

with total_orders_items as (
    select 
        order_id,
        round(sum(total_amount),2) as total_amount_per_order
    from order_items
    group by order_id
),
order_detail as (
    select 
        o.customer_id,
        c.first_name,
        c.city,
        count(o.order_id) as total_orders,
        round(sum(total_amount_per_order),2) as total_spent
    from orders as o 
    inner join total_orders_items as toi 
        on o.order_id = toi.order_id
    inner join customers as c 
        on o.customer_id = c.customer_id
    where o.order_status = "Delivered"
    group by 
        o.customer_id,
        c.first_name,
        c.city
)

select * 
from order_detail
order by total_spent DESC
limit 10;
